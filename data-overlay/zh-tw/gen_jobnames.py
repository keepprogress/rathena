def zh(job_id, name):
	if job_id in BY_ID:
		return BY_ID[job_id]
	name = re.sub(r' 2ND$', '', name)
	if name.startswith('JT_RUNE_CHICKEN'):
		return ZH['Rune Knight']  # 騎乘狀態
	if name.startswith('Baby ') and name[5:] in ZH:
		return '寶寶' + ZH[name[5:]]
	return ZH.get(name)


